"""Generate crates/lumen-analysis/src/colormaps.rs: 256-entry RGB tables for the
heatmap colormaps (magma, viridis, turbo, RdBu) sampled from matplotlib.

Dev only. Usage: python tools/golden/gen_colormaps.py
Requires matplotlib. magma/viridis are CC0, turbo is Apache-2.0 (Google),
RdBu is ColorBrewer (Apache-2.0 style); all are fine to embed in an MIT app.
"""
import pathlib

import matplotlib

OUT = pathlib.Path(__file__).resolve().parents[2] / "crates/lumen-analysis/src/colormaps.rs"
MAPS = [("MAGMA", "magma"), ("VIRIDIS", "viridis"), ("TURBO", "turbo"), ("RDBU", "RdBu_r")]


def table(name):
    cm = matplotlib.colormaps[name].resampled(256)
    rows = []
    for i in range(256):
        r, g, b, _ = cm(i)
        rows.append((round(r * 255), round(g * 255), round(b * 255)))
    return rows


lines = [
    "//! Colormap tables (256 RGB entries each), generated by",
    "//! `tools/golden/gen_colormaps.py` from matplotlib. Do not edit by hand.",
    "//! RDBU is matplotlib `RdBu_r`: blue for negative, red for positive.",
    "",
]
for const, name in MAPS:
    rows = table(name)
    lines.append(f"pub(crate) static {const}: [[u8; 3]; 256] = [")
    for i in range(0, 256, 8):
        lines.append("    " + " ".join(f"[{r}, {g}, {b}]," for r, g, b in rows[i:i + 8]))
    lines.append("];")
    lines.append("")
OUT.write_text("\n".join(lines), encoding="utf8")
print("wrote", OUT)
